package dev.adrc95.logronobus.core.navigation

import androidx.compose.animation.EnterTransition
import androidx.compose.animation.ExitTransition
import androidx.compose.animation.togetherWith
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.lifecycle.viewmodel.navigation3.rememberViewModelStoreNavEntryDecorator
import androidx.navigation3.runtime.NavEntry
import androidx.navigation3.runtime.NavKey
import androidx.navigation3.runtime.rememberSaveableStateHolderNavEntryDecorator
import androidx.navigation3.ui.NavDisplay
import dev.adrc95.logronobus.core.common.InputOutputAction

@Composable
fun Navigation(
    state: NavigationState,
    modifier: Modifier = Modifier,
    entryProvider: InputOutputAction<NavKey, NavEntry<NavKey>>,
) {
    NavDisplay(
        backStack = state.backStack,
        modifier = modifier,
        onBack = { if (state.backStack.size > 1) state.backStack.removeLastOrNull() },
        sceneStrategies = remember { listOf(SheetSceneStrategy()) },
        transitionSpec = { EnterTransition.None togetherWith ExitTransition.None },
        popTransitionSpec = { EnterTransition.None togetherWith ExitTransition.None },
        predictivePopTransitionSpec = { EnterTransition.None togetherWith ExitTransition.None },
        entryDecorators =
            listOf(
                rememberSaveableStateHolderNavEntryDecorator(),
                rememberViewModelStoreNavEntryDecorator(),
            ),
        entryProvider = entryProvider,
    )
}
